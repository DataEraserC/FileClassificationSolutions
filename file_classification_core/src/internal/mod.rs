// mod.rs
//! 内部数据访问层模块
//!
//! 该模块是应用程序的数据访问层（DAL），负责与数据库进行直接交互，
//! 提供对各个实体表的增删改查操作，以及复杂的条件查询和事务处理功能。
//! 所有数据库操作都通过这个模块进行，确保数据访问的一致性和安全性。

/// 文件-分组关联数据访问模块
/// 
/// 提供对 `file_groups` 表的操作，包括文件与分组之间关联关系的管理
pub mod file_group;

/// 文件数据访问模块
/// 
/// 提供对 `files` 表的操作，包括文件记录的增删改查以及引用计数管理
pub mod files;

/// 分组-标签关联数据访问模块
/// 
/// 提供对 `group_tags` 表的操作，包括分组与标签之间关联关系的管理
pub mod group_tag;

/// 分组数据访问模块
/// 
/// 提供对 `groups` 表的操作，包括分组记录的增删改查以及引用计数管理
pub mod groups;

/// 标签数据访问模块
/// 
/// 提供对 `tags` 表的操作，包括标签记录的增删改查以及引用计数管理
pub mod tags;

// 导入模型模块，供内部模块使用
use super::model::models;

